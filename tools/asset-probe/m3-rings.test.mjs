import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import * as THREE from 'three';
import { resolveGeneratedWorldVisuals, discoverGeneratedMeshPaths } from './generated-world-visual-profile.mjs';
import { createLocalM3Manifest, validateM3Manifest } from './m3-manifest.mjs';
import { buildM3Profile } from './m3-profile.mjs';
import { M3WorldRenderer, displayedRingRadius } from './m3-world-renderer.mjs';
import { displayedSurfaceRadius, templateDisplayFactor } from './m3-presentation.mjs';
import { profileTexturePlan, validateSnapshot } from './m3-world-view.mjs';
import { createSystemOverviewPreset } from './m3-camera.mjs';

const root=process.env.STELLARIS_GAME_ROOT,manifestPath=process.env.RINGS_SERVER_MANIFEST;
test('RINGS-01: реальная shared closure, C#/JS digest, conditional mesh, alpha/scale/bounds/nonpicking/lifecycle', {skip:!root||!manifestPath}, async()=>
{
    const read=path=>{const b=readFileSync(root+'/'+path);return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength);};
    const exists=path=>existsSync(root+'/'+path);
    const ids=['pc_continental','pc_gas_giant'];
    const graph=resolveGeneratedWorldVisuals(ids,read,{exists});
    const ring=graph.bindings.find(b=>b.kind==='decoration');
    assert.equal(ring.entityName,'gas_giant_rings_01_entity'); assert.equal(ring.scale,1);
    assert.equal(ring.meshPath,'gfx/models/planets/gas_giant_rings_01.mesh');
    assert.ok(discoverGeneratedMeshPaths(ids,read).includes(ring.meshPath));
    assert.equal(ring.dependencies.filter(p=>p.endsWith('.dds')).length,3);
    assert.ok(ring.meshes.every(m=>m.material.shader==='PdxMeshPlanetRings'&&m.positions.length>0));
    assert.throws(()=>resolveGeneratedWorldVisuals(ids,read,{exists:p=>exists(p)&&!p.endsWith('ring_tiling_normal.dds')}));
    const manifest=await validateM3Manifest(JSON.parse(readFileSync(manifestPath,'utf8')));
    const buffers=new Map(manifest.files.map(f=>[f.relativePath,read(f.relativePath)]));
    assert.deepEqual(await createLocalM3Manifest(buffers,{generatedRequirements:manifest.generatedRequirements}),manifest);
    const profile=buildM3Profile(buffers,{generatedRequirements:manifest.generatedRequirements});
    assert.equal(profile.generatedBindings.size,2); assert.equal(profile.samples.size,6); assert.ok(profileTexturePlan(profile).convertedBytes>0);
    const value=Object.create(M3WorldRenderer.prototype);
    Object.assign(value,{disposed:false,resources:null,profile:null,profileReady:false,current:null,previous:null,retiredSessions:new Set(),fresh:false,needsFreshSnapshot:false,contextLost:false,selection:null,commandFleetId:null,view:{kind:'galaxy'},viewResources:null,callbacks:{},scene:new THREE.Scene(),renderer:{renderLists:{dispose(){}}},resetCamera(){},stageGeneratedGpu(){}});
    value.setProfile(profile);
    const template=value.resources.templates.get('world.pc_gas_giant'),ringTemplate=value.resources.ringTemplate;
    const body={id:'ringed',systemId:'s',kind:'planet',name:'Гигант',visualId:'world.pc_gas_giant',worldClassId:'pc_gas_giant',scale:2,hasRing:true,localPosition:{x:100,z:0}};
    const state={protocol:2,sessionId:'rings',sequence:1,you:1,participants:[],spatial:{systems:[{id:'s',name:'Система',starClassId:'sc_g',radius:400,galaxyPosition:{x:0,y:0,z:0}}],bodies:[body,{...body,id:'bare',hasRing:false,localPosition:{x:-100,z:0}}],colonies:[],fleets:[],hyperlanes:[]}};
    validateSnapshot(state);
    const bad=structuredClone(state);bad.spatial.bodies[0].hasRing='yes';assert.throws(()=>validateSnapshot(bad));
    value.applySnapshot(state); value.showSystem('s');
    const view=value.viewResources,clone=view.group.getObjectByName('planet-rings:ringed');
    assert.ok(clone); assert.equal(view.group.getObjectByName('planet-rings:bare'),undefined);
    assert.equal(template.getObjectByName('planet-rings:ringed'),undefined);
    assert.equal(clone.scale.x,ringTemplate.scale.x*body.scale*templateDisplayFactor(template,body.visualId));
    const mesh=clone.children[0],material=mesh.material;
    assert.equal(material.side,THREE.DoubleSide);assert.equal(material.transparent,true);assert.equal(material.depthWrite,false);assert.equal(material.blending,THREE.NormalBlending);
    assert.ok(material.map&&material.normalMap&&material.specularMap);assert.equal(material.map.wrapS,THREE.RepeatWrapping);
    assert.ok(!view.picks.includes(mesh)); assert.ok(view.bounds.max.x>=100+displayedRingRadius(ringTemplate,template,body)/Math.SQRT2-1e-3);
    const radius=displayedSurfaceRadius(template,body.visualId,body.scale),outer=displayedRingRadius(ringTemplate,template,body);
    assert.ok(outer>radius);
    value.camera=new THREE.PerspectiveCamera(45,16/9,.01,10000);value.controls={target:new THREE.Vector3(),update(){}};value.cancelPointer=()=>{};
    value.setCameraPreset('system-overview');const expected=createSystemOverviewPreset(100+Math.max(radius,outer)+12,16/9);assert.ok(value.camera.position.distanceTo(expected.position)<1e-5);
    let sharedDisposed=0;mesh.geometry.addEventListener('dispose',()=>sharedDisposed++);material.addEventListener('dispose',()=>sharedDisposed++);
    const replacement=structuredClone(state);replacement.sequence=2;replacement.spatial.bodies[0].hasRing=false;value.applySnapshot(replacement);
    assert.equal(value.viewResources.group.getObjectByName('planet-rings:ringed'),undefined);assert.equal(sharedDisposed,0);
    value.showGalaxy();value.showSystem('s');assert.equal(sharedDisposed,0);
    value.releaseView(value.viewResources);value.releaseProfile(value.resources);assert.equal(sharedDisposed,2);
});
